void TFT_Clear(uint16_t color)
{
    unsigned int i, m;
    TFT_SetRegion(0, 0, TFT_WIDTH - 1, TFT_HEIGHT - 1);
    for (i = 0; i < TFT_WIDTH; i++)
        for (m = 0; m < TFT_HEIGHT; m++)
            TFT_WriteData16(color);
    cursorX = 0U;
    cursorY = 0U;
}

void TFT_ClearLine(uint8_t y, uint16_t color)
{
    unsigned int i;
    TFT_SetRegion(0, y, TFT_WIDTH - 1, y + 15);
    for (i = 0; i < TFT_WIDTH; i++)
        for (int m = 0; m < 16; m++)
            TFT_WriteData16(color);
}

/* 鎵归噺缁樺埗: 涓€娆etRegion + 128鍍忕礌杩炵画鍐欏叆 */
static void show_char(uint8_t x, uint8_t y, char ch, uint16_t fg, uint16_t bg)
{
    uint8_t i, j, k;
    if ((uint8_t)ch < 32) return;
    k = (uint8_t)ch - 32;
    if (k > 94) k = 0;

    TFT_SetRegion(x, y, x + 7, y + 15);      /* 涓€娆¤缃?脳16鍖哄煙 */
    for (i = 0; i < 16; i++) {
        uint8_t d = font[(uint16_t) k * 16U + i];
        for (j = 0; j < 8; j++)
            TFT_WriteData16((d & (0x80 >> j)) ? fg : bg);
    }
}

void TFT_SetCursor(uint8_t x, uint8_t y)
{
    cursorX = (x < TFT_WIDTH) ? x : 0U;
    cursorY = (y < TFT_HEIGHT) ? y : 0U;
}

void TFT_WriteChar(char character)
{
    if ((cursorX + 8U) > TFT_WIDTH) {
        cursorX = 0U;
        cursorY = (uint8_t) (cursorY + 16U);
    }
    if ((cursorY + 16U) > TFT_HEIGHT) return;
    show_char(cursorX, cursorY, character, TFT_COLOR_WHITE, TFT_COLOR_BLACK);
    cursorX = (uint8_t) (cursorX + 8U);
}

void TFT_WriteString(const char *text)
{
    while ((text != 0) && (*text != '\0')) TFT_WriteChar(*text++);
}

void TFT_WriteUInt(uint32_t value)
{
    char text[11];
    uint8_t length = 0U;
    do {
        text[length++] = (char) ('0' + (value % 10U));
        value /= 10U;
    } while (value != 0U);
    while (length != 0U) TFT_WriteChar(text[--length]);
}

void TFT_WriteInt(int32_t value)
{
    if (value < 0) {
        TFT_WriteChar('-');
        TFT_WriteUInt((uint32_t) (-(value + 1)) + 1U);
    } else {
        TFT_WriteUInt((uint32_t) value);
    }
}

void TFT_WriteFloat2(float value)
{
    int32_t scaled = (int32_t) ((value >= 0.0f) ?
        (value * 100.0f + 0.5f) : (value * 100.0f - 0.5f));
    uint32_t magnitude;

    if (scaled < 0) {
        TFT_WriteChar('-');
        magnitude = (uint32_t) (-(scaled + 1)) + 1U;
    } else {
        magnitude = (uint32_t) scaled;
    }
    TFT_WriteUInt(magnitude / 100U);
    TFT_WriteChar('.');
    TFT_WriteChar((char) ('0' + ((magnitude / 10U) % 10U)));
    TFT_WriteChar((char) ('0' + (magnitude % 10U)));
}
