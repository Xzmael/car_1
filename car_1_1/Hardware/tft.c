static void hw_spi_w8(uint8_t data)  { DL_SPI_transmitData8(TFT_SPI_INST, data); while (DL_SPI_isBusy(TFT_SPI_INST)) { } }
static void hw_spi_w16(uint16_t d)  { hw_spi_w8(d>>8); hw_spi_w8(d&0xFF); }

static void TFT_WriteCommand(uint8_t idx) { TFT_CS(0); TFT_DC(0); hw_spi_w8(idx); }
static void TFT_WriteData(uint8_t dat)  { TFT_CS(0); TFT_DC(1); hw_spi_w8(dat); }
static void TFT_WriteData16(uint16_t dat) { TFT_CS(0); TFT_DC(1); hw_spi_w16(dat); }

static void TFT_WriteReg(uint8_t idx, uint8_t dat)
{
    TFT_WriteCommand(idx);
    TFT_WriteData(dat);
}

