#define TFT_RES(value) ((value) ? DL_GPIO_setPins(TFT_CTRL_PORT, TFT_CTRL_RES_PIN) : DL_GPIO_clearPins(TFT_CTRL_PORT, TFT_CTRL_RES_PIN))
#define TFT_DC(value)  ((value) ? DL_GPIO_setPins(TFT_CTRL_PORT, TFT_CTRL_DC_PIN) : DL_GPIO_clearPins(TFT_CTRL_PORT, TFT_CTRL_DC_PIN))
#define TFT_CS(value)  ((value) ? DL_GPIO_setPins(TFT_CTRL_PORT, TFT_CTRL_CS_PIN) : DL_GPIO_clearPins(TFT_CTRL_PORT, TFT_CTRL_CS_PIN))
#define TFT_BL(value)  ((value) ? DL_GPIO_setPins(TFT_CTRL_PORT, TFT_CTRL_BLK_PIN) : DL_GPIO_clearPins(TFT_CTRL_PORT, TFT_CTRL_BLK_PIN))

